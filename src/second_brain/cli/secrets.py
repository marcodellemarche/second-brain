"""The `secrets/` folder of an instance: generated values, and empty files for the rest.

Two kinds of secret, handled differently on purpose:

- internal ones (the MCP bearer token, the webhook HMAC secrets, the outbox secret, the SearXNG
  key) are values we and only we use, so `sb init` generates them. The same brain initialised
  twice gets two different sets, and the guard config of one instance never signs for another.
- external ones (the model key, the Telegram or Slack tokens, the calendar token, the terminal
  ssh key) have to come from a service, so the file is created empty and named in the README.

No file in `secrets/` is ever written twice: not by a second `sb init`, not with `--force`. A
regenerated token would silently invalidate a running deployment, and a regenerated model key
would not exist on the other side at all.
"""

from __future__ import annotations

import os
import secrets
import shutil
import subprocess
from dataclasses import dataclass
from pathlib import Path

SECRETS_DIR = "secrets"
SECRET_MODE = 0o600
TOKEN_BYTES = 32

# Names of the generated values. The rendered files reference these by path.
TOOLS_TOKEN = "tools_token"
WEBHOOK_INGEST = "webhook_ingest"
WEBHOOK_RESEARCH = "webhook_research"
WEBHOOK_IDEA = "webhook_idea"
WEBHOOK_SCHEDULE = "webhook_schedule"
OUTBOX_SECRET = "outbox_secret"
SEARXNG_KEY = "searxng_key"
TERMINAL_SSH_KEY = "terminal_ssh_key"
TERMINAL_SSH_PUBKEY = "terminal_ssh_key.pub"
TERMINAL_HOST_KEY = "terminal_host_key"
TERMINAL_HOST_PUBKEY = "terminal_host_key.pub"

# Names of the values that come from a service.
MODEL_API_KEY = "model_api_key"
CALENDAR_TOKEN = "calendar_token"

# The generated values, in the order the README lists them.
GENERATED = (
    TOOLS_TOKEN,
    WEBHOOK_INGEST,
    WEBHOOK_RESEARCH,
    WEBHOOK_IDEA,
    WEBHOOK_SCHEDULE,
    OUTBOX_SECRET,
    SEARXNG_KEY,
)

# What a human has to fill in, and where it comes from. The README is built from this.
EXTERNAL: tuple[tuple[str, str], ...] = (
    (MODEL_API_KEY, "The API key of the model endpoint, the real one. Only the model gate reads it."),
    ("telegram_bot_token", "The bot token from @BotFather. Only for a Telegram brain."),
    ("slack_bot_token", "The bot token (xoxb-...) of the Slack app. Only for a Slack brain."),
    ("slack_app_token", "The app-level token (xapp-...) for Socket Mode. Only for a Slack brain."),
    (CALENDAR_TOKEN, "The OAuth access token of the Google account that owns the calendars."),
    (
        TERMINAL_SSH_KEY,
        "The private key Hermes uses to reach the terminal container. Generated by `sb init` when "
        "`ssh-keygen` is available; otherwise create it with "
        "`ssh-keygen -t ed25519 -N '' -f secrets/terminal_ssh_key`, and the terminal's host key "
        "the same way with `secrets/terminal_host_key`.",
    ),
)

HERMES_ENV = "hermes.env"


class SecretUnreadable(RuntimeError):
    """A secret on disk belongs to a container uid, so this user cannot read it back."""

    def __init__(self, name: str) -> None:
        super().__init__(name)
        self.name = name


@dataclass(frozen=True, slots=True)
class SecretsPlan:
    """What `sb init` wants in `secrets/`: generated values, empty files, and the env file."""

    generated: dict[str, str]
    external: tuple[str, ...]
    ssh_keypair: bool


def plan(*, channel: str, calendar: bool) -> SecretsPlan:
    """Every secret this instance needs. A Slack brain has no Telegram token and the other way round."""
    generated = {name: secrets.token_urlsafe(TOKEN_BYTES) for name in GENERATED}
    external = [
        MODEL_API_KEY,
        "telegram_bot_token" if channel == "Telegram" else "slack_bot_token",
    ]
    if channel == "Slack":
        external.append("slack_app_token")
    if calendar:
        external.append(CALENDAR_TOKEN)
    return SecretsPlan(generated=generated, external=tuple(external), ssh_keypair=True)


def write_secrets(
    directory: Path, plan_: SecretsPlan, *, ssh_keygen: str | None = None
) -> tuple[dict[str, str], list[str]]:
    """Create the secrets folder, never replacing a file that is already there.

    Returns the generated values as they are on disk, which is what the rendered config has to
    use: after a rerun the file holds the first run's value, not the one generated now.
    """
    directory.mkdir(parents=True, exist_ok=True)
    os.chmod(directory, 0o700)
    created: list[str] = []
    for name, value in plan_.generated.items():
        created += create_file(directory / name, value + "\n")
    for name in plan_.external:
        created += create_file(directory / name, "")
    if plan_.ssh_keypair:
        keygen = ssh_keygen or shutil.which("ssh-keygen")
        created += _ssh_keypair(directory, TERMINAL_SSH_KEY, keygen)
        created += _ssh_keypair(directory, TERMINAL_HOST_KEY, keygen)
    created += create_file(directory / "README.md", secrets_readme(plan_), mode=0o600)
    values = {name: read_value(directory / name) for name in plan_.generated}
    created += create_file(directory / HERMES_ENV, hermes_env(values), mode=SECRET_MODE)
    return values, created


def hermes_env(values: dict[str, str]) -> str:
    """The managed env scope: the values Hermes can only take as environment variables.

    Hermes wants the MCP token and the webhook secrets from the environment, not from a file.
    The chat tokens stay empty: they come from a service and only a human can paste them.
    """
    lines = [
        "# Hermes' managed env scope. Values generated by `sb init`, read-only in the container.",
        f"TOOLS_TOKEN={values[TOOLS_TOKEN]}",
        "TELEGRAM_BOT_TOKEN=",
        "SLACK_BOT_TOKEN=",
        "SLACK_APP_TOKEN=",
        f"WEBHOOK_SECRET_INGEST={values[WEBHOOK_INGEST]}",
        f"WEBHOOK_SECRET_RESEARCH={values[WEBHOOK_RESEARCH]}",
        f"WEBHOOK_SECRET_IDEA={values[WEBHOOK_IDEA]}",
        f"WEBHOOK_SECRET_SCHEDULE={values[WEBHOOK_SCHEDULE]}",
        f"HERMES_OUTBOX_SECRET={values[OUTBOX_SECRET]}",
        "",
    ]
    return "\n".join(lines)


def secrets_readme(plan_: SecretsPlan) -> str:
    """What goes in each file. Regenerated on every run, so it always lists the current plan."""
    lines = [
        "# Secrets",
        "",
        "One file per secret, mounted read-only into the one container that reads it. Nothing here",
        "is committed, and `sb init` never overwrites a file that already exists.",
        "",
        "## Fill these in",
        "",
    ]
    for name, description in EXTERNAL:
        if name in plan_.external or name == TERMINAL_SSH_KEY:
            lines.append(f"- `{name}`: {description}")
    lines += [
        "",
        "`hermes.env` is the one exception: Hermes wants the MCP token, the chat token and the",
        "webhook secrets as environment values, so they are also rendered there, from these files.",
        "`sb init` writes it once; fill in the chat token and re-render it if you change a value.",
        "",
        "## Generated, nothing to do",
        "",
    ]
    for name in plan_.generated:
        lines.append(f"- `{name}`: generated by `sb init`.")
    lines += [
        "",
        f"`{TERMINAL_HOST_KEY}` is the ssh host key of the terminal container, mounted at "
        "`/etc/ssh/terminal_host_key` and generated by `sb init` when `ssh-keygen` is available. It "
        "has to outlive a rebuild: one made inside the image changes every time, and Hermes keeps "
        "the old one in its known_hosts.",
        "",
        'Do not regenerate these to "start clean": a new MCP token or webhook secret invalidates',
        "the running containers, and `sb init` will not overwrite them for the same reason.",
        "",
    ]
    return "\n".join(lines)


def read_value(path: Path) -> str:
    """The secret as the containers read it: the file, without its trailing newline."""
    try:
        return path.read_text(encoding="utf-8").strip()
    except PermissionError as exc:
        raise SecretUnreadable(path.name) from exc


def create_file(path: Path, content: str, *, mode: int = SECRET_MODE) -> list[str]:
    """Write the file only when it is absent, so a second run cannot rotate a live secret.

    An existing file is left as it is, mode included: after `owners.sh` it belongs to a container
    uid, and the operator running `sb init --force` can no longer chmod or rewrite it.
    """
    if path.exists():
        return []
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL
    descriptor = os.open(path, flags, mode)
    with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
        handle.write(content)
    os.chmod(path, mode)
    return [path.name]


def _ssh_keypair(directory: Path, name: str, ssh_keygen: str | None) -> list[str]:
    """Generate one keypair when ssh-keygen exists; the README says what to do otherwise."""
    private = directory / name
    if private.exists():
        return []
    if ssh_keygen is None:
        create_file(private, "")
        return [private.name]
    result = subprocess.run(
        [ssh_keygen, "-q", "-t", "ed25519", "-N", "", "-C", "brain-terminal", "-f", str(private)],
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode != 0:
        create_file(private, "")
        return [private.name]
    os.chmod(private, SECRET_MODE)
    public = directory / f"{name}.pub"
    if public.exists():
        os.chmod(public, 0o644)
    return [private.name, public.name]
